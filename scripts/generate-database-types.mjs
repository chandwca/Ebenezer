import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

// Keep CLI warnings/credentials out of the generated source, and preserve the old
// file if generation fails. This always targets the local, migrated database.
const root = fileURLToPath(new URL('../', import.meta.url));
const result = spawnSync(
  'pnpm',
  [
    'exec',
    'supabase',
    'gen',
    'types',
    'typescript',
    '--local',
    '--schema',
    'ebenezer_api,ebenezer_private',
  ],
  {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 10 * 1024 * 1024,
  },
);
if (result.status !== 0 || !result.stdout.includes('export type Database')) {
  console.error(
    'Database type generation failed. Start local Supabase and apply migrations first.',
  );
  process.exit(1);
}
mkdirSync(new URL('../apps/api/src/database/', import.meta.url), { recursive: true });
writeFileSync(
  new URL('../apps/api/src/database/database.types.ts', import.meta.url),
  await format(
    '// Generated by pnpm db:types from the local migrated schema. Do not edit.\n' + result.stdout,
    {
      ...(await resolveConfig(
        fileURLToPath(new URL('../apps/api/src/database/database.types.ts', import.meta.url)),
      )),
      parser: 'typescript',
    },
  ),
);
console.log('Generated apps/api/src/database/database.types.ts');
